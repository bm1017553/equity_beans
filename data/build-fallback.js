// Regenerates data/fallback.js from the JSON files in this folder.
//
// Browsers block fetch() when a page is opened straight from disk (file://),
// so app.js falls back to this script-tag copy of the data. The JSON files stay
// the source of truth (they're what gets imported into MongoDB later).
//
// Run after editing any JSON file:   node data/build-fallback.js
const fs = require("fs");
const path = require("path");

const files = ["products.json", "reviews.json"];
const data = {};
for (const file of files) {
  const raw = fs.readFileSync(path.join(__dirname, file), "utf8");
  data[`data/${file}`] = JSON.parse(raw);
}

const output = `// GENERATED by data/build-fallback.js. Do not edit by hand; edit the JSON files and rerun it.
// Used only when fetch() can't load the JSON files (e.g. the page was opened from disk).
window.EQUITY_FALLBACK_DATA = ${JSON.stringify(data, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, "fallback.js"), output);
console.log(`Wrote data/fallback.js (${files.join(", ")})`);
